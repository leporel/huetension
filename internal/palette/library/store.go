package library

import (
	"errors"
	"fmt"
	"strings"
	"sync"
	"sync/atomic"

	"github.com/leporel/huetension/internal/color"
)

// SavedCategory is force-added to every palette created through Save, so
// user-added palettes stay separable from the curated defaults.
const SavedCategory = "Saved"

// ErrNotPersistable is returned by Store.Save when the store has no
// on-disk path — the catalogue is read-only and cannot grow.
var ErrNotPersistable = errors.New("library: saving is unavailable (no on-disk path configured)")

// ErrPersist wraps a failure to write the catalogue to disk. Save
// returns it so callers can tell a storage fault (retryable, an
// operator problem) apart from a validation fault (the caller's input).
var ErrPersist = errors.New("library: failed to persist the catalogue")

// Store holds a catalogue that can grow at runtime. The index lives
// behind an atomic pointer so readers never block a save; mu serialises
// the read-modify-write of a Save itself. The old Index is never
// mutated — Save publishes a freshly built one — so an in-flight reader
// keeps a consistent view.
//
// path is the on-disk library.json a Save persists to. Empty means the
// catalogue is in-memory only and Save returns ErrNotPersistable.
type Store struct {
	idx  atomic.Pointer[Index]
	mu   sync.Mutex
	path string
}

// NewStore wraps an index and the on-disk path a Save persists to. idx
// may be nil (no catalogue configured); path may be empty (the
// catalogue is read-only on this server).
func NewStore(idx *Index, path string) *Store {
	s := &Store{path: path}
	s.idx.Store(idx)
	return s
}

// Index returns the catalogue snapshot visible right now. Lock-free — a
// reader never blocks a save, which publishes its result wholesale.
func (s *Store) Index() *Index {
	if s == nil {
		return nil
	}
	return s.idx.Load()
}

// Path returns the on-disk library.json location, or "" when the
// catalogue is in-memory only.
func (s *Store) Path() string {
	if s == nil {
		return ""
	}
	return s.path
}

// CanSave reports whether Save can persist a palette — a configured
// catalogue plus an on-disk path.
func (s *Store) CanSave() bool {
	return s != nil && s.path != "" && s.idx.Load() != nil
}

// SaveInput is the content of a user palette to add. The ID is
// generated by Save — callers never supply it (the server owns IDs).
type SaveInput struct {
	Name        string
	Description string
	Colors      []string
	Categories  []string
	Tags        []string
}

// Save validates in, generates a unique slug ID, force-adds the
// SavedCategory, appends the palette, persists the whole catalogue to
// disk, and publishes the new index. It returns the stored palette
// (with its generated ID and canonicalised colours).
//
// Errors: ErrNotPersistable when the store has no path; ErrPersist
// (wrapped) when the disk write fails; a plain validation error
// otherwise (empty name, no colours, an unparseable colour, ...).
func (s *Store) Save(in SaveInput) (Palette, error) {
	if s == nil || s.idx.Load() == nil {
		return Palette{}, errors.New("library: catalogue is not configured")
	}
	if s.path == "" {
		return Palette{}, ErrNotPersistable
	}
	name := strings.TrimSpace(in.Name)
	if name == "" {
		return Palette{}, errors.New("library: palette name is required")
	}
	if len(in.Colors) == 0 {
		return Palette{}, errors.New("library: at least one color is required")
	}
	// Re-parse every colour so the stored hex is canonical (#rrggbb) and
	// an unparseable colour is rejected before the disk write.
	hexes := make([]string, len(in.Colors))
	for i, raw := range in.Colors {
		c, err := color.Parse(strings.TrimSpace(raw))
		if err != nil {
			return Palette{}, fmt.Errorf("library: colors[%d] %q: %w", i, raw, err)
		}
		hexes[i] = c.Hex()
	}

	// Serialise the read-modify-write: concurrent saves must not race on
	// ID generation or clobber each other's library.json.
	s.mu.Lock()
	defer s.mu.Unlock()

	cur := s.idx.Load()
	id := GenerateID(name, func(id string) bool {
		_, taken := cur.Get(id)
		return taken
	})
	next, err := cur.Add(Palette{
		ID:          id,
		Name:        name,
		Description: strings.TrimSpace(in.Description),
		Categories:  mergeSavedCategory(in.Categories),
		Tags:        trimAll(in.Tags),
		Colors:      hexes,
	})
	if err != nil {
		return Palette{}, err
	}
	if err := Save(s.path, next); err != nil {
		return Palette{}, fmt.Errorf("%w: %v", ErrPersist, err)
	}
	s.idx.Store(next)

	stored, _ := next.Get(id)
	return stored, nil
}

// mergeSavedCategory prepends SavedCategory, then appends the trimmed,
// non-empty extras — skipping any that duplicate SavedCategory.
func mergeSavedCategory(extra []string) []string {
	cats := []string{SavedCategory}
	for _, raw := range extra {
		c := strings.TrimSpace(raw)
		if c != "" && !strings.EqualFold(c, SavedCategory) {
			cats = append(cats, c)
		}
	}
	return cats
}

// trimAll returns the trimmed, non-empty members of in — used to
// sanitise the free-form tags list before it is persisted.
func trimAll(in []string) []string {
	out := make([]string, 0, len(in))
	for _, raw := range in {
		if v := strings.TrimSpace(raw); v != "" {
			out = append(out, v)
		}
	}
	return out
}
